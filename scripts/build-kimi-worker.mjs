import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const schema=fs.readFileSync(new URL('research/schema.js',root),'utf8').replace(/^export /gm,'');
const themePolicy=fs.readFileSync(new URL('research/theme-policy.js',root),'utf8').replace(/^export /gm,'');
const enrichmentSchema=fs.readFileSync(new URL('research/enrichment-schema.js',root),'utf8').replace(/^export /gm,'');
const enrichmentCore=fs.readFileSync(new URL('services/enrichment-core.js',root),'utf8').replace(/^import .*?;\n/gm,'').replace(/^export /gm,'');
const worker=fs.readFileSync(new URL('services/kimi-core.js',root),'utf8').replace(/^import .*?;\n/gm,'').replace(/^export (?!default)/gm,'');
fs.writeFileSync(new URL('services/kimi-worker.js',root),'// Generated by scripts/build-kimi-worker.mjs. No secrets belong in this file.\n'+schema+'\n'+themePolicy+'\n'+enrichmentSchema+'\n'+enrichmentCore+'\n'+worker);
console.log('Prepared standalone Kimi analysis worker.');
