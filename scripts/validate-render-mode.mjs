import assert from 'node:assert/strict';
import {displayState,applySurfaceMode,isOccludedByShell} from '../anatomy/render-mode.js';
const base={renderMode:'transparent',focusKind:'entry',selected:'cit-21',isolate:false};
assert.equal(displayState(base,true).isolate,false);
assert.equal(displayState({...base,renderMode:'solid'},true).isolate,true);
assert.equal(displayState({...base,renderMode:'solid',focusKind:'group'},true).isolate,true);
assert.equal(displayState({...base,renderMode:'solid'},false).isolate,false);
assert.equal(displayState({...base,renderMode:'solid',focusKind:'evidence'},true).isolate,true);
assert.equal(displayState({...base,isolate:true},true).isolate,true);
assert.equal(base.isolate,false,'Auto-isolation must not overwrite the manual transparency preference');
const material={transparent:true,opacity:.18,depthWrite:false,depthTest:false,emissiveIntensity:.65,updates:0,set needsUpdate(value){if(value)this.updates++;}};
const style={opacity:.97,depthWrite:false,depthTest:false,emissiveIntensity:.65};
applySurfaceMode(material,style,'solid');
assert.equal(material.transparent,false);assert.equal(material.opacity,1);assert(material.depthWrite&&material.depthTest);assert(material.emissiveIntensity<=.08);assert.equal(material.updates,1);
applySurfaceMode(material,style,'solid');assert.equal(material.updates,1,'No redundant shader recompilation');
applySurfaceMode(material,style,'transparent');
assert.equal(material.opacity,.97);assert.equal(material.transparent,true);assert.equal(material.depthWrite,false);assert.equal(material.depthTest,false);assert.equal(material.emissiveIntensity,.65);assert.equal(material.updates,2);
assert(isOccludedByShell(30,20,true));assert(!isOccludedByShell(20,30,true));assert(!isOccludedByShell(30,20,false));assert(!isOccludedByShell(30,undefined,true));
console.log('Render mode policies passed: reversible opacity/depth state, automatic isolation, manual-state preservation and opaque-shell picking.');
